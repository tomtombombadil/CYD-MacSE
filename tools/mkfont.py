# Makes components/macui/font.h: a 1-bit proportional font for the touch
# keys, rendered from DejaVu Sans Bold (free licence; see font.h).
# Run once on a PC with Python + Pillow: python tools/mkfont.py <font.ttf>
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE, H, BASE = 13, 16, 12   # pixel size, cell height, baseline row
f = ImageFont.truetype(ttf, SIZE)
chars = [chr(c) for c in range(32, 127)] + ["←", "↑", "→", "↓", "⌘", "⌥"]
glyphs = []
for ch in chars:
    w = max(1, int(round(f.getlength(ch))))
    if ch == " ":
        w = 4
    im = Image.new("L", (w + 4, H), 0)
    d = ImageDraw.Draw(im)
    d.text((1, BASE), ch, font=f, fill=255, anchor="ls")
    px = im.load()
    cols = [x for x in range(im.width) if any(px[x, y] >= 110 for y in range(H))]
    if cols and ch != " ":
        x0, x1 = min(cols), max(cols)
    else:
        x0, x1 = 0, w - 1
    gw = x1 - x0 + 1
    rows = []
    for y in range(H):
        v = 0
        for x in range(gw):
            if px[x0 + x, y] >= 110:
                v |= 1 << (15 - x)
        rows.append(v)
    glyphs.append((ch, gw, rows))

out = ["// Generated by tools/mkfont.py from DejaVu Sans Bold %dpx (DejaVu fonts:" % SIZE,
       "// free licence, Bitstream Vera derived - https://dejavu-fonts.github.io).",
       "// Glyphs 32..126, then arrows left up right down, command, option (127..132).",
       "#pragma once", "#include <stdint.h>",
       "#define FONT_H %d" % H, "#define FONT_BASE %d" % BASE, "#define FONT_FIRST 32",
       "#define FONT_COUNT %d" % len(glyphs),
       "static const uint8_t kFontW[FONT_COUNT] = {" + ",".join(str(g[1]) for g in glyphs) + "};",
       "static const uint16_t kFontBits[FONT_COUNT][FONT_H] = {"]
for ch, gw, rows in glyphs:
    out.append("    {" + ",".join("0x%04x" % r for r in rows) + "},  // " + (repr(ch)))
out.append("};")
open(sys.argv[2] if len(sys.argv) > 2 else "../components/macui/font.h", "w").write("\n".join(out) + "\n")
print("ok", len(glyphs))
